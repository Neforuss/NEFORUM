// Writes lib/src/text/emoji_tables.dart from Unicode's emoji-test.txt, the
// vendored copy in test/fixtures/unicode. Run from packages/neforum_core:
//
//   dart run tool/generate_emoji_tables.dart
//
// test/text_counter_conformance_test.dart fails when the table and the vendored
// file disagree.
import 'dart:io';

/// The tables [source] (the text of emoji-test.txt) gives: flat start, end pairs.
({List<int> bases, List<int> presentation}) emojiTablesFrom(String source) {
  final bases = <int>{}, presentation = <int>{};
  for (final line in source.split('\n')) {
    if (line.startsWith('#') || !line.contains(';')) continue;
    final runes = [for (final h in line.split(';').first.trim().split(' ')) int.parse(h, radix: 16)];
    final status = line.split(';')[1].split('#').first.trim();
    bases.add(runes.first);
    if (runes.length == 1 && (status == 'fully-qualified' || status == 'component')) presentation.add(runes.single);
  }
  return (bases: _ranges(bases), presentation: _ranges(presentation));
}

List<int> _ranges(Set<int> values) {
  final sorted = values.toList()..sort();
  final out = <int>[];
  for (final v in sorted) {
    if (out.isNotEmpty && out.last == v - 1) {
      out.last = v;
    } else {
      out
        ..add(v)
        ..add(v);
    }
  }
  return out;
}

String _table(String name, String doc, List<int> ranges) {
  final b = StringBuffer('/// $doc\nconst List<int> $name = [\n');
  for (var i = 0; i < ranges.length; i += 2) {
    b.writeln('  0x${ranges[i].toRadixString(16).toUpperCase()}, 0x${ranges[i + 1].toRadixString(16).toUpperCase()},');
  }
  b.writeln('];');
  return '$b';
}

void main() {
  final source = File('test/fixtures/unicode/emoji-test.txt').readAsStringSync();
  final version = RegExp(r'# Version: (\S+)').firstMatch(source)![1];
  final t = emojiTablesFrom(source);
  File('lib/src/text/emoji_tables.dart').writeAsStringSync('// Generated by tool/generate_emoji_tables.dart from emoji-test.txt $version.\n'
      '// Do not edit.\n\n'
      '${_table('kEmojiBaseRanges', 'Code points an emoji sequence starts with: start, end pairs.', t.bases)}\n'
      '${_table('kEmojiPresentationRanges', 'Code points that show as an emoji on their own, with no variation selector: start, end pairs.', t.presentation)}');
}
